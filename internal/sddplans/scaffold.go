package sddplans

import (
	"fmt"
	"os"
	"path/filepath"
)

// StarterPlanName is the starter plan's file name. It is fixed, so the
// "already exists" guard means something.
const StarterPlanName = "starter-plan.md"

// StarterPlan is the runnable template Scaffold writes. It is deliberately
// runnable: the headings match what pipeline.ParsePlan requires, so the user
// can edit the bodies and run it without first learning the format from
// source.
const StarterPlan = `---
marshal_plan: 1
name: starter-plan
---

# Starter Plan

Replace this file's tasks with your own, then run it with ` + "`/sdd`" + `.

Each task is executed by a fresh implementer subagent that sees only that
task's body, reviewed by a second subagent, and committed by Marshal itself
once the build and test gate passes. Tasks may also carry deterministic
` + "`marshal.*`" + ` blocks that Marshal applies exactly, with a scoped agent
fallback only where the exact operation is not provable.

## Global Constraints

Requirements that apply to every task. The implementer sees these with each
task, so put project-wide rules here rather than repeating them.

- Every change must keep ` + "`go build ./...`" + ` and ` + "`go test ./...`" + ` passing.
- Match the surrounding code's style; do not restructure unrelated files.

## Task 1: Describe the first unit of work

Write what a competent engineer with no context needs: which files to touch,
what the behavior should be, and how to tell it worked. One task should be
one commit's worth of change.

## Task 2: Describe the second unit of work

Tasks run in order. Task 2 may rely on Task 1 being complete, but its body
must still stand alone — the subagent implementing it never sees Task 1.

## Task 3: Add a marker file

Create a marker file without touching source code.

` + "```marshal.file path=\".marshal/example-marker.txt\"\nThis file is generated by the starter SDD plan.\n```" + `

` + "```marshal.assert\nkind = \"file.exists\"\nfile = \".marshal/example-marker.txt\"\n```" + `
`

// Scaffold writes StarterPlan to plansDir (relative to repoRoot), creating the
// directory. existed is true, and nothing is written, when the file is already
// there. Its errors read "create <dir>: <err>" and "write <path>: <err>".
func Scaffold(repoRoot, plansDir string) (path string, existed bool, err error) {
	dir := filepath.Join(repoRoot, plansDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", false, fmt.Errorf("create %s: %w", dir, err)
	}
	path = filepath.Join(dir, StarterPlanName)
	if _, err := os.Stat(path); err == nil {
		return path, true, nil
	}
	if err := os.WriteFile(path, []byte(StarterPlan), 0o644); err != nil {
		return path, false, fmt.Errorf("write %s: %w", path, err)
	}
	return path, false, nil
}
