#!/usr/bin/env bash
#
# scripts/dev-studio.sh — put this checkout's build in front of the browser
# studio (Marshal Web Studio), without cutting a release.
#
# The studio is the SPA embedded in webbridge (`web/bridge/static`, baked in
# with //go:embed) talking to a webbridge over HTTP. It runs as its own unit,
# `marshal-studio.service`, on 127.0.0.1:7700. One reason it is a second
# daemon rather than the TUI's: it serves the browser on that address with its
# own bearer token, and it restarts apart from the TUI's daemon, so a restart
# here does not end the TUI's turns. Containers are no longer a reason to keep
# it apart — every daemon runs them now.
#
# The loop is the daemon's: the unit pins binary *paths*, so rebuild in place
# and restart. A change under app/ is invisible until `flutter build web`
# rewrites web/bridge/static and webbridge is relinked, because //go:embed bakes
# those files into it — which is what the default run does.
#
# There is no hot-reload mode. F8's cutover retired the Svelte studio, its Vite
# dev server and the proxy that made one possible: the browser client is
# same-origin only (`WebTransport` with no base, app/lib/src/client), so a page
# served by a dev server on another port would send every /api request to that
# dev server instead of the bridge. Edit, run this script, reload.
#
#   scripts/dev-studio.sh                 # build SPA + binaries, restart, print status
#   scripts/dev-studio.sh --no-build      # restart the binaries already on disk
#   scripts/dev-studio.sh --no-spa        # rebuild Go only; keep the embedded SPA
#   scripts/dev-studio.sh --no-restart    # build only; the running studio keeps the old binary
#   scripts/dev-studio.sh --install       # rewrite the unit and token, then restart
#   scripts/dev-studio.sh --status        # print status; build and restart nothing
#   scripts/dev-studio.sh --token         # print the bearer token the SPA asks for
#   scripts/dev-studio.sh --dev-image     # also refresh the agent image from ./marshal (fast)
#   scripts/dev-studio.sh --agent-image   # also rebuild the container agent image (slow)
#
#   --timeout SECS   how long to wait for the studio to answer (default 30)
#   --force          install even though a location variable points outside $HOME
#   -h, --help       this text
#
# The SPA authenticates /api with a bearer token held in localStorage and asks
# for it once per browser, so `--token` is how you fetch it to paste. The token
# lives in a 0600 env file beside the unit's other state; it is only
# regenerated by --install or when the file is missing, so restarts keep the
# browser signed in.
#
# The unit binds 127.0.0.1:7700, so another machine reaches studio only
# through a forward (see "Reaching studio from another machine" in
# docs/dev-loop.md). --status prints every `tailscale serve` origin that
# proxies to that loopback port, because the printed loopback URL is not
# what a remote browser types and the tailnet root may belong to another
# service.
#
# Agents the studio spawns run in containers: the studio's projects have a
# workspace, and a daemon containerises an agent that has one whenever a
# rootless podman or docker is present (a rootful docker is refused on Linux).
# There is no host-process fallback for a workspace agent — --marshal-bin only
# reaches agents without one — so a spawn without a usable runtime answers 501,
# and every spawn needs the agent image. For a source build the default is
# `ghcr.io/marshal/agent:latest`. The studio itself serves without it; only
# spawning agents needs it, which is most of what the studio is for.
#
# The agent's marshal comes from the *image*, not from --marshal-bin, so this
# is a third artifact to refresh alongside the SPA and the two binaries: a host
# rebuild does not reach agents inside containers.
#
#   --dev-image   builds build/Dockerfile.dev, which COPYs the host-built
#                 ./marshal into a base matching this machine's release. The
#                 copy makes it seconds, and it is tagged :latest so the
#                 studio's default settings resolve to it — this is the one to
#                 use on the dev loop.
#   --agent-image builds build/Dockerfile, which compiles marshal in a
#                 golang builder stage. Portable, publishable, and slow: it
#                 recompiles the module and runs on the release base, whose
#                 glibc this host cannot link against.
#
# `--status` says when the image is missing or older than ./marshal.
#
# The state dir is a host directory, `$data_dir/studio/state`: agent containers
# bind subpaths of it, so the bridge and its containers see the same files, and
# the user's config home is bound read-only beside it. On Linux a container
# needs the state dir bind-mounted, so a rootless podman or docker is required
# and a rootful one is refused. `--status` prints the directory.
#
# `go build ./cmd/marshal ./cmd/webbridge` without -o only type-checks the two
# mains and writes nothing; `-o .` is what puts both binaries in the repo root,
# which is the path the unit holds. CGO is required: tree-sitter
# (internal/repo/symbols.go) links a C library.
#
# Like the daemon's script, this deliberately does not watch the tree: a
# restart ends the studio's running agents, so run it between turns.

set -euo pipefail

repo_root=$(cd -P "$(dirname "$0")/.." && pwd -P)
cd "$repo_root"

build=1
spa=1
restart=1
install=0
force=0
status=0
print_token=0
agent_image=0
dev_image=0
timeout=30

base=http://127.0.0.1:7700

# agent_image_ref is the tag the bridge resolves for a source build: a dev
# version has no published tag to pin to, so defaultAgentImageFor answers
# :latest. Both image builds tag this, so the studio's default project
# settings resolve to whatever was built here.
agent_image_ref=ghcr.io/marshal/agent:latest

usage() {
	awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0"
}

while [ $# -gt 0 ]; do
	case $1 in
	--no-build)
		build=0
		spa=0
		;;
	--no-spa) spa=0 ;;
	--no-restart) restart=0 ;;
	--install) install=1 ;;
	--status)
		build=0
		spa=0
		restart=0
		status=1
		;;
	--token)
		# A query: stdout must be the token alone, so the caller can use it
		# directly (`curl -H "Authorization: Bearer $(... --token)"`).
		print_token=1
		build=0
		spa=0
		restart=0
		;;
	--agent-image) agent_image=1 ;;
	--dev-image) dev_image=1 ;;
	--force) force=1 ;;
	--timeout)
		shift
		if [ $# -eq 0 ]; then
			echo "dev-studio.sh: --timeout wants whole seconds" >&2
			exit 2
		fi
		case $1 in
		'' | *[!0-9]*)
			echo "dev-studio.sh: --timeout wants whole seconds, got '$1'" >&2
			exit 2
			;;
		esac
		timeout=$1
		;;
	-h | --help)
		usage
		exit 0
		;;
	*)
		echo "dev-studio.sh: unknown option '$1' (try --help)" >&2
		exit 2
		;;
	esac
	shift
done

if [ "$(uname -s)" != "Linux" ]; then
	echo "dev-studio.sh: this writes a systemd user unit, so it is Linux-only (this is $(uname -s))" >&2
	echo "dev-studio.sh: run webbridge yourself elsewhere" >&2
	exit 1
fi

unit_path="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user/marshal-studio.service"

# The studio's directory mirrors the daemon's data dir, then adds /studio, so
# it never shares a fleet, state dir or lock with the local daemon.
if [ -n "${MARSHAL_DATA_DIR:-}" ]; then
	data_dir="$MARSHAL_DATA_DIR"
elif [ -n "${XDG_DATA_HOME:-}" ]; then
	data_dir="$XDG_DATA_HOME/marshal"
else
	data_dir="$HOME/.local/share/marshal"
fi
studio_dir="$data_dir/studio"
env_file="$studio_dir/webbridge.env"
token_file="$studio_dir/token"
log="$studio_dir/webbridge.log"

runtime=$(command -v podman || command -v docker || true)
state_dir=$studio_dir/state

under_home() {
	case $1 in
	"$HOME" | "$HOME"/*) return 0 ;;
	*) return 1 ;;
	esac
}

# check_location_env guards the one irreversible half: the unit bakes the
# resolved studio directory, so running this from a test shell that pointed
# MARSHAL_DATA_DIR or XDG_DATA_HOME at a temp dir would pin the service there
# for good.
check_location_env() {
	local var value outside="" inside=""
	for var in MARSHAL_CONFIG_DIR MARSHAL_DATA_DIR XDG_CONFIG_HOME XDG_DATA_HOME; do
		value=${!var:-}
		[ -n "$value" ] || continue
		if under_home "$value"; then
			inside="$inside $var=$value"
		else
			outside="$outside $var=$value"
		fi
	done
	if [ -n "$outside" ] && [ "$force" -eq 0 ]; then
		printf 'dev-studio.sh: refusing to write a unit that pins these paths:%s\n' "$outside" >&2
		printf 'dev-studio.sh: the unit bakes the studio directory, so the service would\n' >&2
		printf 'dev-studio.sh: outlive it. Unset them, or pass --force.\n' >&2
		exit 1
	fi
	if [ -n "$inside" ]; then
		printf 'note: the unit will pin%s\n' "$inside"
	fi
}

# ensure_token writes the bearer token once. Regenerating it on every restart
# would sign every open browser out.
ensure_token() {
	[ -s "$env_file" ] && [ -s "$token_file" ] && [ "$install" -eq 0 ] && return 0
	local tok
	mkdir -p "$studio_dir"
	tok=$(head -c 32 /dev/urandom | od -An -v -tx1 | tr -d ' \n')
	(umask 077 && printf 'WEBBRIDGE_TOKEN=%s\n' "$tok" >"$env_file")
	printf '%s\n' "$tok" >"$token_file"
	chmod 600 "$env_file" "$token_file"
	echo "wrote a new bearer token to $token_file"
}

read_token() {
	if [ ! -s "$env_file" ]; then
		echo "dev-studio.sh: no token at $env_file; run --install first" >&2
		exit 1
	fi
	sed -n 's/^WEBBRIDGE_TOKEN=//p' "$env_file" | head -n 1
}

# write_unit renders the unit for this checkout. --cwd-root registers the repo
# as the studio's first project (a daemon given none registers no working
# directory project).
write_unit() {
	mkdir -p "$(dirname "$unit_path")" "$state_dir"
	cat >"$unit_path" <<EOF
[Unit]
Description=Marshal studio (webbridge)

[Service]
WorkingDirectory=$repo_root
ExecStart="$repo_root/webbridge" "--socket" "$studio_dir/marshal.sock" "--addr" "127.0.0.1:7700" "--state-dir" "$state_dir" "--egress" "on" "--workspace" "$studio_dir/fleet.json" "--cwd-root" "$repo_root" "--marshal-bin" "$repo_root/marshal"
EnvironmentFile=$env_file
Environment="PATH=$HOME/.local/bin:$HOME/bin:/usr/local/bin:/usr/bin:/bin"
Environment="SHELL=/bin/bash"
Restart=on-failure
StandardOutput=append:$log
StandardError=append:$log

[Install]
WantedBy=default.target
EOF
	echo "wrote $unit_path"
}

wait_ready() {
	local token deadline
	token=$(read_token)
	deadline=$(($(date +%s) + timeout))
	while :; do
		# /api/projects is behind the bearer check, so a healthy daemon
		# answers it without needing any particular route set.
		if curl -fsS -m 2 -H "Authorization: Bearer $token" "$base/api/projects" >/dev/null 2>&1; then
			return 0
		fi
		if [ "$(date +%s)" -ge "$deadline" ]; then
			return 1
		fi
		sleep 0.2
	done
}

# remote_urls prints the origins another machine can reach this studio on:
# every `tailscale serve` entry whose proxy target is the studio's own
# listen port. The unit binds loopback, so these entries are the only
# off-box route that needs no extra work, and the tailnet root is usually
# someone else's service (443 here proxies :8200). Prints nothing when no
# entry forwards to the port, or when tailscale is absent.
remote_urls() {
	command -v tailscale >/dev/null 2>&1 || return 0
	tailscale serve status 2>/dev/null | awk -v port="${base##*:}" '
		$1 ~ /^https?:\/\// { url = $1; next }
		$NF ~ ("^https?://(127\\.0\\.0\\.1|localhost|\\[::1\\]):" port "$") && url != "" {
			print url
		}
	' || true
}

print_status() {
	local token state pid started version runtime img_epoch bin_epoch remotes
	token=$(read_token)
	state=$(systemctl --user is-active marshal-studio.service 2>/dev/null || true)
	pid=$(systemctl --user show -p MainPID --value marshal-studio.service 2>/dev/null || true)
	started=$(systemctl --user show -p ActiveEnterTimestamp --value marshal-studio.service 2>/dev/null || true)
	version=$(./webbridge --version 2>/dev/null || true)
	printf 'unit:    %s (marshal-studio.service)\n' "${state:-unknown}"
	printf 'unit:    %s\n' "$unit_path"
	printf 'state:   %s\n' "$state_dir"
	if curl -fsS -m 2 -H "Authorization: Bearer $token" "$base/api/projects" >/dev/null 2>&1; then
		printf 'studio:  %s  pid=%s  started %s\n' \
			"${version#webbridge }" "$pid" "${started:-?}"
		printf 'url:     %s\n' "$base"
		remotes=$(remote_urls)
		if [ -n "$remotes" ]; then
			while IFS= read -r remote; do
				printf 'remote:  %s/\n' "$remote"
			done <<<"$remotes"
		else
			printf 'note:    loopback only; another machine needs a forward to :%s\n' "${base##*:}"
			printf 'note:    tailscale serve --bg --https=8443 %s\n' "${base##*:}"
		fi
		printf 'token:   %s\n' "$token"
	else
		printf 'studio:  not answering on %s\n' "$base"
	fi
	runtime=$(command -v podman || command -v docker || true)
	if [ -n "$runtime" ]; then
		if ! "$runtime" image inspect "$agent_image_ref" >/dev/null 2>&1; then
			printf 'note:    no %s image; spawning an agent needs one\n' "$agent_image_ref"
			printf 'note:    scripts/dev-studio.sh --dev-image builds it from ./marshal in seconds\n'
		else
			# build_dev_image stamps ./marshal's mtime into the image, so
			# staleness is a comparison of two integers. The image's own
			# created time cannot be used: podman prints it with nanoseconds,
			# which date -d refuses, and it is not what the agent runs.
			bin_epoch=$(stat -c %Y ./marshal 2>/dev/null || true)
			stamp=$("$runtime" image inspect -f '{{index .Labels "marshal.dev.bin-mtime"}}' "$agent_image_ref" 2>/dev/null || true)
			case $stamp in
			'' | *[!0-9]*) ;;
			*)
				if [ -n "$bin_epoch" ] && [ "$bin_epoch" -gt "$stamp" ]; then
					printf 'note:    %s was built from an older ./marshal; agents would run a stale build\n' "$agent_image_ref"
					printf 'note:    scripts/dev-studio.sh --dev-image refreshes it\n'
				fi
				;;
			esac
		fi
	fi
}

# ---------------------------------------------------------------- build ----

# flutter_ready names the toolchain the SPA build needs. F8's cutover retired
# the Svelte studio with its Node toolchain, so the build is `flutter build web`
# run from app/ — there is no npm step and no web/ui to install into.
flutter_ready() {
	if ! command -v flutter >/dev/null 2>&1; then
		echo "dev-studio.sh: flutter is missing, so the SPA cannot be built" >&2
		echo "dev-studio.sh: install Flutter 3.50+, or pass --no-spa to rebuild Go only" >&2
		exit 1
	fi
	if [ ! -f app/pubspec.yaml ]; then
		echo "dev-studio.sh: app/pubspec.yaml is missing, so this checkout has no Studio to build" >&2
		exit 1
	fi
}

if [ "$spa" -eq 1 ]; then
	flutter_ready
	# --base-href / is where the bridge serves the SPA (an old /next/ link
	# redirects there), and --no-web-resources-cdn is not optional: without it
	# the build fetches the CanvasKit engine from gstatic, and a private network
	# that cannot reach that CDN never starts the Studio. --output is relative to
	# app/, which is where the command runs. This overwrites the tracked
	# placeholder web/bridge/static/index.html — that file is not to be
	# committed; CI builds the SPA the same way and embeds it.
	echo "building the SPA into web/bridge/static"
	(cd app && flutter build web --base-href / --no-web-resources-cdn --output ../web/bridge/static)
fi

if [ "$build" -eq 1 ]; then
	echo "building marshal and webbridge"
	CGO_ENABLED=1 go build -o . ./cmd/marshal ./cmd/webbridge
	version=$(./webbridge --version)
	echo "built ${version}"
fi

# host_base_image names the container base whose glibc matches this machine's.
# The fast image copies a host-built binary, and marshal links tree-sitter
# through cgo, so that binary needs a libc at least as new as the one it was
# linked against — debian:bookworm-slim is too old on a Fedora/Ubuntu host
# newer than bookworm, and the mismatch surfaces as "GLIBC_2.x not found".
host_base_image() {
	local os_id os_ver
	os_id=$(. /etc/os-release 2>/dev/null && printf '%s' "${ID:-}")
	os_ver=$(. /etc/os-release 2>/dev/null && printf '%s' "${VERSION_ID:-}")
	case $os_id in
	fedora | debian | ubuntu)
		[ -n "$os_ver" ] || return 1
		printf 'docker.io/library/%s:%s\n' "$os_id" "$os_ver"
		return 0
		;;
	esac
	return 1
}

# build_dev_image refreshes the agent image from the host build. It copies the
# binary instead of compiling it in the image, so a rebuild is a copy rather
# than a module compile — which is what makes it usable on every commit.
build_dev_image() {
	if [ -z "$runtime" ]; then
		echo "dev-studio.sh: --dev-image needs podman or docker on PATH" >&2
		exit 1
	fi
	if [ ! -x ./marshal ]; then
		echo "dev-studio.sh: --dev-image needs ./marshal; drop --no-build" >&2
		exit 1
	fi
	local base ctx stamp
	if ! base=$(host_base_image); then
		base=docker.io/library/debian:stable-slim
		echo "note: no base could be derived from /etc/os-release" >&2
		echo "note: building on ${base}; if the agent reports 'GLIBC_2.x not found'," >&2
		echo "note: rebuild with --build-arg BASE_IMAGE=<an image matching this host>" >&2
	fi
	# The repository root as a build context would hand app/build, the Flutter
	# tree's own artifacts, and .marshal/worktrees to the runtime; the image
	# needs the one binary.
	ctx=$(mktemp -d)
	cp ./marshal "$ctx/marshal"
	# The label records which ./marshal went in, so --status can tell a stale
	# image from a current one by comparing integers.
	stamp=$(stat -c %Y ./marshal)
	echo "building the dev agent image from ./marshal on ${base}"
	if ! "$runtime" build --build-arg "BASE_IMAGE=$base" \
		--label "marshal.dev.bin-mtime=$stamp" \
		-f build/Dockerfile.dev -t "$agent_image_ref" "$ctx"; then
		rm -rf "$ctx"
		return 1
	fi
	rm -rf "$ctx"
}

if [ "$dev_image" -eq 1 ]; then
	build_dev_image
fi

if [ "$agent_image" -eq 1 ]; then
	if [ -z "$runtime" ]; then
		echo "dev-studio.sh: --agent-image needs podman or docker on PATH" >&2
		exit 1
	fi
	# A source build's default image is the untagged-build fallback
	# (defaultAgentImageFor), so tagging :latest is what makes the studio's
	# default project settings resolve to the image built here. It is the slow
	# step: it compiles marshal inside the image, on the release base.
	echo "building the agent image (slow; the agent binary is baked in)"
	"$runtime" build -f build/Dockerfile -t "$agent_image_ref" .
fi

if [ "$print_token" -eq 1 ]; then
	read_token
	exit 0
fi

if [ "$build" -eq 1 ] && [ "$restart" -eq 0 ] && [ "$install" -eq 0 ]; then
	echo "note: the studio was not restarted; it keeps the binary it launched with"
fi

if [ "$status" -eq 1 ]; then
	print_status
	exit 0
fi

# ------------------------------------------------------- install / restart --

if [ "$restart" -eq 1 ] || [ "$install" -eq 1 ]; then
	if [ ! -x "$repo_root/webbridge" ] || [ ! -x "$repo_root/marshal" ]; then
		echo "dev-studio.sh: $repo_root/{marshal,webbridge} are missing; drop --no-build" >&2
		exit 1
	fi
fi

if [ "$install" -eq 1 ] || [ ! -e "$unit_path" ]; then
	check_location_env
	ensure_token
	write_unit
	systemctl --user daemon-reload
	systemctl --user enable marshal-studio.service
elif [ "$restart" -eq 1 ]; then
	ensure_token
fi

if [ "$restart" -eq 1 ] || [ "$install" -eq 1 ]; then
	echo "restarting the studio"
	systemctl --user restart marshal-studio.service
	if ! wait_ready; then
		echo "dev-studio.sh: the studio did not answer on $base within ${timeout}s" >&2
		echo "dev-studio.sh: last lines of $log" >&2
		tail -n 20 "$log" >&2 || true
		echo "dev-studio.sh: journalctl --user -u marshal-studio says why" >&2
		exit 1
	fi
fi

print_status
