// Package dartgen writes the Dart module for a contract package (F1).
// Standard library only: it reads the package's syntax, never its compiled
// types. It is tsgen's sibling — the same parse, the same rejections, a
// different target language.
//
// The rules, from docs/studio-flutter/plans/2026-11-17-f1-client-plan.md:
//
//   - one Dart class per Go struct, with the Go name unchanged;
//   - one Dart enum per Go string type, its constants in lower camel case
//     plus `unknown`, so a state a newer bridge sends is preserved;
//   - JSON keys from the struct tags, Dart field names in lower camel case;
//   - optional (`omitempty` or pointer) fields nullable;
//   - Go doc comments carried over;
//   - a construct tsgen rejects is rejected here by the same name.
//
// A class that holds an enum field also holds `rawEnums`: the wire text of
// every enum value this build has no constant for, keyed by JSON name, so a
// round trip writes back what the bridge said instead of `unknown`.
package dartgen

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"strconv"
	"strings"
	"unicode"
)

// header is the module's first lines: what wrote the file and how to write
// it again. `dart format off` holds the module's layout still: it is emitted
// to be read, and reformatting it would move every declaration on every
// formatter release without changing what it says.
const header = `// Code generated by web/bridge/contract/dartgen. DO NOT EDIT.
// Regenerate with: go test ./web/bridge/contract/dartgen -run TestDartContractIsCurrent -update
//
// dart format off
`

// kind is what a package-level named type means to the generator.
type kind int

const (
	// kindUnsupported is a named type the module cannot declare. A field
	// naming one is an error, never a reference to a Dart type that does
	// not exist. It is the zero kind, so a name the package never declared
	// is unsupported too.
	kindUnsupported kind = iota
	// kindString is a named string type: it becomes an enum, or a typedef
	// when it has no constants.
	kindString
	// kindStruct is a named struct: it becomes a class.
	kindStruct
	// kindInterface is a named interface, which the plan does not map.
	kindInterface
)

// file is one parsed source file, in lexical filename order.
type file struct {
	path string
	ast  *ast.File
}

// constDecl is one constant of a named string type: its name and the
// expression that gives its value.
type constDecl struct {
	name string
	expr ast.Expr
}

// generator holds the parsed package: the declarations to emit, the
// constants that name their values, and the helpers the emitted code calls.
type generator struct {
	fset  *token.FileSet
	files []*file
	kinds map[string]kind
	// constructs names the unsupported construct of each declared type the
	// module cannot map, so a field naming it says why.
	constructs map[string]string
	// rawTypes holds each declared type's underlying expression, so a type
	// declared as another type can be resolved.
	rawTypes map[string]ast.Expr
	// consts holds each named string type's constant values, in
	// declaration order.
	consts map[string][]string
	// constDecls holds each named string type's constant declarations, in
	// declaration order.
	constDecls map[string][]constDecl
	// constExprs holds every constant's value expression, by name, so a
	// constant that takes its value from another constant resolves.
	constExprs map[string]ast.Expr
	// used holds the helpers the emitted declarations call, so the module
	// declares each of them once and none of them unused.
	used map[string]bool
}

// Generate reads the Go files of the package in dir, test files excluded,
// and returns the Dart module: a header line, the helpers the declarations
// call, then each named string type as an enum and each struct as a class,
// files in name order and declarations in source order.
func Generate(dir string) ([]byte, error) {
	g, err := newGenerator(dir)
	if err != nil {
		return nil, err
	}
	if err := g.collect(); err != nil {
		return nil, err
	}
	return g.render()
}

// newGenerator parses the Go files of the package in dir, test files
// excluded, in lexical filename order.
func newGenerator(dir string) (*generator, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}

	g := &generator{
		fset:       token.NewFileSet(),
		kinds:      make(map[string]kind),
		constructs: make(map[string]string),
		rawTypes:   make(map[string]ast.Expr),
		consts:     make(map[string][]string),
		constDecls: make(map[string][]constDecl),
		constExprs: make(map[string]ast.Expr),
		used:       make(map[string]bool),
	}

	pkg := ""
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		path := filepath.Join(dir, name)
		f, err := parser.ParseFile(g.fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		if pkg == "" {
			pkg = f.Name.Name
		} else if f.Name.Name != pkg {
			pos := g.fset.Position(f.Name.Pos())
			return nil, fmt.Errorf("%s:%d: package %q, want %q", pos.Filename, pos.Line, f.Name.Name, pkg)
		}
		g.files = append(g.files, &file{path: path, ast: f})
	}

	return g, nil
}

// collect records each package-level type's kind and each named string
// type's typed constants, both in source order across files.
func (g *generator) collect() error {
	// The types come first, in their own pass: a constant may name a type
	// declared later, or in a later file.
	if err := g.collectTypes(); err != nil {
		return err
	}
	g.resolveTypes()
	if err := g.collectConstants(); err != nil {
		return err
	}
	return g.resolveConstants()
}

// collectTypes records what each package-level type declaration means.
func (g *generator) collectTypes() error {
	for _, f := range g.files {
		for _, decl := range f.ast.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				if !ts.Name.IsExported() {
					// An unexported type is a package-internal helper, not part
					// of the wire: the module declares only what a client can
					// receive, so a journal's legacy form stays the bridge's.
					continue
				}
				if ts.TypeParams != nil && ts.TypeParams.NumFields() > 0 {
					return g.unsupported(ts.Pos(), "generic type")
				}
				if ts.Assign.IsValid() {
					// An alias names another type, and the generator
					// maps types by declaration, not by target.
					g.kinds[ts.Name.Name] = kindUnsupported
					g.constructs[ts.Name.Name] = "type alias"
					continue
				}
				k, construct := classify(ts.Type, ts.Name.Name)
				g.kinds[ts.Name.Name] = k
				g.rawTypes[ts.Name.Name] = ts.Type
				if construct != "" {
					g.constructs[ts.Name.Name] = construct
				}
			}
		}
	}
	return nil
}

// resolveTypes settles each type declared as another type. One declared as a
// named string type is a string type itself, and its own constants make its
// enum.
func (g *generator) resolveTypes() {
	for name := range g.rawTypes {
		if g.kinds[name] != kindUnsupported {
			continue
		}
		ident, ok := g.rawTypes[name].(*ast.Ident)
		if !ok {
			continue
		}
		if g.stringKind(ident.Name, map[string]bool{}) {
			g.kinds[name] = kindString
			g.constructs[name] = ""
		}
	}
}

// stringKind reports whether the named type is a string type, following the
// chain of types declared as other types.
func (g *generator) stringKind(name string, seen map[string]bool) bool {
	if seen[name] {
		return false
	}
	seen[name] = true
	switch g.kinds[name] {
	case kindString:
		return true
	case kindUnsupported:
	default:
		return false
	}
	expr, ok := g.rawTypes[name]
	if !ok {
		return false
	}
	ident, ok := expr.(*ast.Ident)
	if !ok {
		return false
	}
	return g.stringKind(ident.Name, seen)
}

// collectConstants records each named string type's typed constants, in
// declaration order across files.
func (g *generator) collectConstants() error {
	for _, f := range g.files {
		for _, decl := range f.ast.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.CONST {
				continue
			}
			// A const block may omit an expression list, which repeats the
			// previous non-empty list and its type.
			var lastValues []ast.Expr
			var lastType ast.Expr
			for _, spec := range gd.Specs {
				vs, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				values, typ := vs.Values, vs.Type
				if len(values) == 0 {
					values = lastValues
					if typ == nil {
						typ = lastType
					}
				} else {
					lastValues, lastType = values, vs.Type
				}
				for i, name := range vs.Names {
					if i >= len(values) {
						break
					}
					// Every constant's expression is recorded, so a
					// constant that takes its value from another
					// constant resolves.
					g.constExprs[name.Name] = values[i]
					id, ok := typ.(*ast.Ident)
					if !ok || g.kinds[id.Name] != kindString {
						continue
					}
					g.constDecls[id.Name] = append(g.constDecls[id.Name], constDecl{name: name.Name, expr: values[i]})
				}
			}
		}
	}
	return nil
}

// resolveConstants turns each named string type's constant declarations into
// their values, in declaration order.
func (g *generator) resolveConstants() error {
	for name, decls := range g.constDecls {
		values := make([]string, 0, len(decls))
		for _, d := range decls {
			value, err := g.constValue(d.expr, map[string]bool{})
			if err != nil {
				return err
			}
			values = append(values, value)
		}
		g.consts[name] = values
	}
	return nil
}

// constValue reads one constant's value: a string literal, or the value of
// the constant it names.
func (g *generator) constValue(expr ast.Expr, seen map[string]bool) (string, error) {
	switch t := expr.(type) {
	case *ast.BasicLit:
		if t.Kind != token.STRING {
			return "", g.unsupported(t.Pos(), "constant value")
		}
		value, err := strconv.Unquote(t.Value)
		if err != nil {
			return "", g.unsupported(t.Pos(), "constant value")
		}
		return value, nil
	case *ast.ParenExpr:
		return g.constValue(t.X, seen)
	case *ast.Ident:
		if seen[t.Name] {
			return "", g.unsupported(t.Pos(), "constant value")
		}
		next, ok := g.constExprs[t.Name]
		if !ok {
			return "", g.unsupported(t.Pos(), fmt.Sprintf("constant %q", t.Name))
		}
		seen[t.Name] = true
		defer delete(seen, t.Name)
		return g.constValue(next, seen)
	default:
		return "", g.unsupported(expr.Pos(), "constant value")
	}
}

// classify records what a type declaration may be referenced as, and the
// construct to name when it has no Dart mapping. A named type the module
// cannot declare is unsupported: a field naming it would be a reference to
// a Dart type that does not exist.
func classify(expr ast.Expr, name string) (kind, string) {
	switch t := expr.(type) {
	case *ast.StructType:
		return kindStruct, ""
	case *ast.InterfaceType:
		return kindInterface, "interface"
	case *ast.Ident:
		if t.Name == "string" {
			return kindString, ""
		}
		// A type declared as another type: it is settled once every
		// type is known.
		return kindUnsupported, ""
	case *ast.ChanType:
		return kindUnsupported, "channel"
	case *ast.FuncType:
		return kindUnsupported, "function type"
	case *ast.ArrayType:
		if t.Len != nil {
			return kindUnsupported, "array"
		}
		return kindUnsupported, "slice"
	case *ast.MapType:
		key, ok := t.Key.(*ast.Ident)
		if !ok || key.Name != "string" {
			return kindUnsupported, "map keyed by a non-string"
		}
		return kindUnsupported, "map"
	case *ast.StarExpr:
		return kindUnsupported, "pointer type"
	case *ast.IndexExpr, *ast.IndexListExpr:
		return kindUnsupported, "generic type"
	default:
		return kindUnsupported, fmt.Sprintf("named type %q", name)
	}
}

// unsupported names the file, line and construct that has no mapping.
func (g *generator) unsupported(pos token.Pos, construct string) error {
	p := g.fset.Position(pos)
	return fmt.Errorf("%s:%d: unsupported %s", p.Filename, p.Line, construct)
}

// writeDoc renders a Go doc comment as Dart `///` lines, each indented by
// indent. An absent or empty comment writes nothing. Angle brackets are
// escaped: Dart reads a doc comment as Markdown, and a bare `<name>` there
// is an HTML tag, which the analyzer reports.
func writeDoc(b *strings.Builder, doc *ast.CommentGroup, indent string) {
	if doc == nil {
		return
	}
	text := strings.TrimSuffix(doc.Text(), "\n")
	if text == "" {
		return
	}
	text = strings.ReplaceAll(text, "&", "&amp;")
	text = strings.ReplaceAll(text, "<", "&lt;")
	text = strings.ReplaceAll(text, ">", "&gt;")
	for _, line := range strings.Split(text, "\n") {
		if line == "" {
			b.WriteString(indent + "///\n")
			continue
		}
		b.WriteString(indent + "/// " + line + "\n")
	}
}

// render emits the module: the header, a blank line, the helpers a
// declaration calls, then one block per declaration, separated by blank
// lines, ending with exactly one newline.
func (g *generator) render() ([]byte, error) {
	var blocks []string
	for _, f := range g.files {
		for _, decl := range f.ast.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				doc := ts.Doc
				if doc == nil && len(gd.Specs) == 1 {
					doc = gd.Doc
				}

				var block string
				var err error
				switch g.kinds[ts.Name.Name] {
				case kindString:
					block, err = g.stringDecl(ts.Name.Name, doc)
				case kindStruct:
					block, err = g.structClass(ts.Name.Name, ts.Type.(*ast.StructType), doc)
				default:
					continue
				}
				if err != nil {
					return nil, err
				}
				blocks = append(blocks, block)
			}
		}
	}

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n")
	var parts []string
	parts = append(parts, g.helperBlocks()...)
	parts = append(parts, blocks...)
	b.WriteString(strings.Join(parts, "\n\n"))
	b.WriteString("\n")
	return []byte(b.String()), nil
}

// helperBlocks returns the declarations of the helpers the emitted code
// calls, in a fixed order.
func (g *generator) helperBlocks() []string {
	var blocks []string
	for _, h := range helpers {
		if !g.used[h.name] {
			continue
		}
		blocks = append(blocks, strings.TrimSuffix(h.code, "\n"))
	}
	return blocks
}

// helper is one private function the generated types call.
type helper struct {
	name string
	code string
}

// helpers are the decoder functions, in the order the module declares them.
// Each is emitted only when a declaration calls it.
var helpers = []helper{
	{"_object", `/// The object [json] names, decoded by [fromJson].
T _object<T>(
  Object? json,
  T Function(Map<String, dynamic> json) fromJson,
) => fromJson(json as Map<String, dynamic>);
`},
	{"_objectOrNull", `/// The object [json] names, or null when it is absent.
T? _objectOrNull<T>(
  Object? json,
  T Function(Map<String, dynamic> json) fromJson,
) => json == null ? null : fromJson(json as Map<String, dynamic>);
`},
	{"_list", `/// The array [json] names, each element decoded by [convert], or an empty
/// list when it is absent. Go writes a nil slice as ` + "`null`" + `, so a required
/// array can arrive null and means empty.
List<T> _list<T>(Object? json, T Function(Object? value) convert) =>
    json == null
    ? <T>[]
    : [for (final value in json as List<dynamic>) convert(value)];
`},
	{"_listOrNull", `/// The array [json] names, or null when it is absent, each element
/// decoded by [convert].
List<T>? _listOrNull<T>(Object? json, T Function(Object? value) convert) =>
    json == null
    ? null
    : [for (final value in json as List<dynamic>) convert(value)];
`},
	{"_map", `/// The object [json] names, each value decoded by [convert], or an empty
/// map when it is absent. Go writes a nil map as ` + "`null`" + `, so a required
/// object can arrive null and means empty.
Map<String, T> _map<T>(Object? json, T Function(Object? value) convert) =>
    json == null
    ? <String, T>{}
    : {
        for (final entry in (json as Map<String, dynamic>).entries)
          entry.key: convert(entry.value),
      };
`},
	{"_mapOrNull", `/// The object [json] names, or null when it is absent, each value
/// decoded by [convert].
Map<String, T>? _mapOrNull<T>(Object? json, T Function(Object? value) convert) =>
    json == null
    ? null
    : {
        for (final entry in (json as Map<String, dynamic>).entries)
          entry.key: convert(entry.value),
      };
`},
	{"_enumOrNull", `/// The enum value [json] names, or null when it is absent.
T? _enumOrNull<T>(Object? json, T Function(String wire) fromWire) =>
    json == null ? null : fromWire(json as String);
`},
}

// stringDecl emits a named string type: an enum of its constants plus
// `unknown`, or a typedef when it has none.
func (g *generator) stringDecl(name string, doc *ast.CommentGroup) (string, error) {
	var b strings.Builder
	writeDoc(&b, doc, "")
	decls := g.constDecls[name]
	values := g.consts[name]
	if len(decls) == 0 {
		if doc == nil {
			fmt.Fprintf(&b, "/// %s is a named string with no fixed values.\n", name)
		}
		fmt.Fprintf(&b, "typedef %s = String;", name)
		return b.String(), nil
	}

	seen := map[string]bool{"unknown": true}
	idents := make([]string, len(decls))
	for i, d := range decls {
		ident, err := lowerCamel(d.name)
		if err != nil {
			return "", g.unsupported(d.expr.Pos(), err.Error())
		}
		if seen[ident] {
			return "", fmt.Errorf("%s: constant %s maps to the Dart name %q twice", d.name, d.name, ident)
		}
		seen[ident] = true
		idents[i] = ident
	}

	fmt.Fprintf(&b, "enum %s {\n", name)
	for i, ident := range idents {
		fmt.Fprintf(&b, "  %s(%s),\n", ident, dartString(values[i]))
	}
	fmt.Fprintf(&b, "  unknown('unknown');\n\n")
	fmt.Fprintf(&b, "  const %s(this.wire);\n\n", name)
	b.WriteString("  /// The wire text this value stands for.\n")
	b.WriteString("  final String wire;\n\n")
	fmt.Fprintf(&b, "  /// The value [wire] names, or [unknown] when this build does not\n")
	fmt.Fprintf(&b, "  /// know it.\n")
	fmt.Fprintf(&b, "  static %s fromWire(String wire) {\n", name)
	b.WriteString("    for (final value in values) {\n")
	b.WriteString("      if (value != unknown && value.wire == wire) {\n")
	b.WriteString("        return value;\n")
	b.WriteString("      }\n")
	b.WriteString("    }\n")
	b.WriteString("    return unknown;\n")
	b.WriteString("  }\n")
	b.WriteString("}")
	return b.String(), nil
}

// dartString renders a Go string value as a single-quoted Dart literal.
func dartString(value string) string {
	var b strings.Builder
	b.WriteByte('\'')
	for _, r := range value {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '\'':
			b.WriteString(`\'`)
		case '$':
			b.WriteString(`\$`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 {
				fmt.Fprintf(&b, `\u%04x`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('\'')
	return b.String()
}

// field is one exported field of a struct, as Dart sees it.
type field struct {
	// dartName is the Go field name in lower camel case.
	dartName string
	jsonName string
	doc      *ast.CommentGroup
	comment  *ast.CommentGroup
	// omitempty is true when the wire omits the field when empty.
	omitempty bool
	desc      *typeDesc
}

// null reports whether the field's Dart type is nullable: a pointer, an
// `omitempty` field, or a raw JSON value that may be null.
func (f *field) null() bool {
	return f.omitempty || f.desc.nullable || f.desc.kind == typeRaw
}

// text is the field's Dart type.
func (f *field) text() string {
	d := f.desc.dartText()
	if f.omitempty && !strings.HasSuffix(d, "?") {
		d += "?"
	}
	return d
}

// required reports whether the constructor takes the field as `required`:
// the wire always sends it. That does not promise a non-null value — Go
// writes a nil slice or map as `null`, so a required list or map can arrive
// null, and `_list` and `_map` decode that as empty.
func (f *field) required() bool {
	return !f.omitempty && !f.desc.nullable
}

// structClass emits one Dart class for a Go struct.
func (g *generator) structClass(name string, st *ast.StructType, doc *ast.CommentGroup) (string, error) {
	fields, err := g.fields(st)
	if err != nil {
		return "", err
	}
	hasEnums := false
	for _, f := range fields {
		if f.desc.kind == typeEnum {
			hasEnums = true
		}
	}

	var b strings.Builder
	writeDoc(&b, doc, "")
	fmt.Fprintf(&b, "class %s {\n", name)

	if len(fields) == 0 && !hasEnums {
		fmt.Fprintf(&b, "  const %s();\n\n", name)
	} else {
		fmt.Fprintf(&b, "  const %s({\n", name)
		for _, f := range fields {
			prefix := "    this."
			if f.required() {
				prefix = "    required this."
			}
			fmt.Fprintf(&b, "%s%s,\n", prefix, f.dartName)
		}
		if hasEnums {
			b.WriteString("    this.rawEnums = const {},\n")
		}
		b.WriteString("  });\n\n")
	}

	for _, f := range fields {
		writeDoc(&b, f.doc, "  ")
		if f.doc == nil {
			writeDoc(&b, f.comment, "  ")
		}
		fmt.Fprintf(&b, "  final %s %s;\n", f.text(), f.dartName)
	}
	if len(fields) > 0 {
		b.WriteString("\n")
	}
	if hasEnums {
		b.WriteString("  /// The wire text of each enum field this build has no value\n")
		b.WriteString("  /// for, keyed by JSON name, so a round trip keeps it.\n")
		b.WriteString("  final Map<String, String> rawEnums;\n\n")
	}

	b.WriteString("  factory " + name + ".fromJson(Map<String, dynamic> json) {\n")
	if hasEnums {
		b.WriteString("    final rawEnums = <String, String>{};\n")
	}
	for _, f := range fields {
		if f.desc.kind != typeEnum {
			continue
		}
		for _, line := range g.enumLocals(f) {
			b.WriteString("    " + line + "\n")
		}
	}
	if len(fields) == 0 {
		fmt.Fprintf(&b, "    return const %s();\n", name)
	} else {
		fmt.Fprintf(&b, "    return %s(\n", name)
		for _, f := range fields {
			for _, line := range g.argLines(f, "      ") {
				b.WriteString(line)
				b.WriteString("\n")
			}
		}
		if hasEnums {
			b.WriteString("      rawEnums: rawEnums,\n")
		}
		b.WriteString("    );\n")
	}
	b.WriteString("  }\n\n")

	b.WriteString("  Map<String, dynamic> toJson() {\n")
	b.WriteString("    final json = <String, dynamic>{};\n")
	for _, f := range fields {
		for _, line := range g.encodeLines(f) {
			b.WriteString(line)
			b.WriteString("\n")
		}
	}
	b.WriteString("    return json;\n")
	b.WriteString("  }\n")
	b.WriteString("}")
	return b.String(), nil
}

// fields reads a struct's exported, wire-visible fields in source order.
func (g *generator) fields(st *ast.StructType) ([]*field, error) {
	var fields []*field
	// seen holds each Dart field name this struct already declares, so two
	// Go names that land on one Dart name is an error rather than a class
	// with the member twice (Foo and FOO both become foo).
	seen := make(map[string]string, len(st.Fields.List))
	for _, f := range st.Fields.List {
		if len(f.Names) == 0 {
			return nil, g.unsupported(f.Pos(), "embedded field")
		}
		for _, ident := range f.Names {
			if !ident.IsExported() {
				continue
			}
			jsonName := ident.Name
			omitempty := false
			if f.Tag != nil {
				raw, err := strconv.Unquote(f.Tag.Value)
				if err != nil {
					return nil, g.unsupported(f.Tag.Pos(), "struct tag")
				}
				if tag := reflect.StructTag(raw).Get("json"); tag != "" {
					parts := strings.Split(tag, ",")
					if parts[0] == "-" {
						continue
					}
					if parts[0] != "" {
						jsonName = parts[0]
					}
					for _, opt := range parts[1:] {
						if opt == "omitempty" {
							omitempty = true
						}
					}
				}
			}
			dartName, err := lowerCamel(ident.Name)
			if err != nil {
				return nil, g.unsupported(ident.Pos(), err.Error())
			}
			// A field whose name is a Dart keyword keeps its JSON name and
			// takes a trailing underscore in Dart: `extends` is a legal JSON
			// key and a reserved word here.
			if dartReserved[dartName] {
				dartName += "_"
			}
			if first, clash := seen[dartName]; clash {
				return nil, g.unsupported(ident.Pos(), fmt.Sprintf("field name collision: %s and %s both map to the Dart name %q", first, ident.Name, dartName))
			}
			seen[dartName] = ident.Name
			desc, err := g.describe(f.Type)
			if err != nil {
				return nil, err
			}
			fields = append(fields, &field{
				dartName:  dartName,
				jsonName:  jsonName,
				doc:       f.Doc,
				comment:   f.Comment,
				omitempty: omitempty,
				desc:      desc,
			})
		}
	}
	return fields, nil
}

// enumLocals emits the statements that decode one enum field and remember
// its wire text when this build does not know the value.
func (g *generator) enumLocals(f *field) []string {
	d := f.desc
	base := f.dartName
	wire := base + "Wire"
	from := d.name + ".fromWire(" + wire + ")"
	lines := []string{"final " + wire + " = json['" + f.jsonName + "'] as String" + nullableMark(f.null()) + ";"}
	if d.nullable || f.omitempty {
		from = "_enumOrNull(" + wire + ", " + d.name + ".fromWire)"
		g.use("_enumOrNull")
	}
	lines = append(lines, "final "+base+" = "+from+";")
	lines = append(lines, "if ("+base+" == "+d.name+".unknown) {")
	raw := wire
	if f.null() {
		raw = wire + "!"
	}
	lines = append(lines, "  rawEnums['"+f.jsonName+"'] = "+raw+";", "}")
	return lines
}

// argLines emits one field's named argument to the generated constructor.
func (g *generator) argLines(f *field, indent string) []string {
	if f.desc.kind == typeEnum {
		return []string{indent + f.dartName + ": " + f.dartName + ","}
	}
	src := "json['" + f.jsonName + "']"
	expr, call, args := g.decode(f.desc, src, f.null())
	if !call {
		return []string{indent + f.dartName + ": " + expr + ","}
	}
	lines := []string{indent + f.dartName + ": " + expr + "("}
	for _, a := range args {
		lines = append(lines, indent+"  "+a+",")
	}
	lines = append(lines, indent+"),")
	return lines
}

// decode renders the Dart expression that decodes src, a `json['x']` lookup
// or a list element, into desc. It reports whether the expression is a call
// the caller must spread over several lines, with one argument per element
// of args.
func (g *generator) decode(desc *typeDesc, src string, null bool) (expr string, call bool, args []string) {
	switch desc.kind {
	case typePrim:
		switch desc.prim {
		case "String", "bool":
			if null {
				return src + " as " + desc.prim + "?", false, nil
			}
			return src + " as " + desc.prim, false, nil
		case "int", "double":
			if null {
				return "(" + src + " as num?)?.to" + numCast(desc.prim) + "()", false, nil
			}
			return "(" + src + " as num).to" + numCast(desc.prim) + "()", false, nil
		}
	case typeRaw:
		return src, false, nil
	case typeStruct:
		if null {
			g.use("_objectOrNull")
			return "_objectOrNull", true, []string{src, desc.name + ".fromJson"}
		}
		g.use("_object")
		return "_object", true, []string{src, desc.name + ".fromJson"}
	case typeEnum:
		if null {
			g.use("_enumOrNull")
			return "_enumOrNull", true, []string{src, desc.name + ".fromWire"}
		}
		return desc.name + ".fromWire(" + src + " as String)", false, nil
	case typeList:
		convert := "(value) => " + mustExpr(g.decode(desc.elem, "value", desc.elem.nullable))
		if null {
			g.use("_listOrNull")
			return "_listOrNull", true, []string{src, convert}
		}
		g.use("_list")
		return "_list", true, []string{src, convert}
	case typeMap:
		convert := "(value) => " + mustExpr(g.decode(desc.elem, "value", desc.elem.nullable))
		if null {
			g.use("_mapOrNull")
			return "_mapOrNull", true, []string{src, convert}
		}
		g.use("_map")
		return "_map", true, []string{src, convert}
	}
	// Every kind above returns; an unsupported expression never reaches
	// here, because describe rejected it.
	panic("dartgen: unreachable decode")
}

// numCast is the `int` or `double` decoder's method name suffix.
func numCast(prim string) string {
	if prim == "int" {
		return "Int"
	}
	return "Double"
}

// mustExpr unwraps a decode expression that is itself a multi-line call,
// which only happens for a container inside a container.
func mustExpr(expr string, _ bool, args []string) string {
	if args == nil {
		return expr
	}
	return expr + "(" + strings.Join(args, ", ") + ")"
}

// use records that the emitted module calls the named helper.
func (g *generator) use(name string) { g.used[name] = true }

// encodeLines emits the statements that write one field to the JSON map.
func (g *generator) encodeLines(f *field) []string {
	if !f.omitempty {
		var body []string
		switch f.desc.kind {
		case typeList:
			body = g.encodeList(f.desc, f.jsonName, f.dartName)
		case typeMap:
			body = g.encodeMap(f.desc, f.jsonName, f.dartName)
		}
		if body != nil {
			lines := make([]string, len(body))
			for i, line := range body {
				lines[i] = "    " + line
			}
			return lines
		}
		write := g.encode(f.desc, f.jsonName, f.dartName)
		return []string{"    json['" + f.jsonName + "'] = " + write + ";"}
	}
	lines := []string{"    if (" + f.dartName + " != null) {"}
	for _, line := range g.encodeGuarded(f.desc, f.jsonName, f.dartName) {
		lines = append(lines, "      "+line)
	}
	lines = append(lines, "    }")
	return lines
}

// encodeGuarded emits the assignment inside an `omitempty` field's null
// check, where the field is known not to be null.
func (g *generator) encodeGuarded(desc *typeDesc, jsonName, dartName string) []string {
	switch desc.kind {
	case typeStruct:
		return []string{"json['" + jsonName + "'] = " + dartName + "!.toJson();"}
	case typeEnum:
		return []string{"json['" + jsonName + "'] = rawEnums['" + jsonName + "'] ?? " + dartName + "!.wire;"}
	case typeList:
		return g.encodeList(desc, jsonName, dartName+"!")
	case typeMap:
		return g.encodeMap(desc, jsonName, dartName+"!")
	}
	return []string{"json['" + jsonName + "'] = " + dartName + ";"}
}

// encode renders the expression that writes one non-omitempty field.
func (g *generator) encode(desc *typeDesc, jsonName, dartName string) string {
	switch desc.kind {
	case typeStruct:
		if desc.nullable {
			return dartName + "?.toJson()"
		}
		return dartName + ".toJson()"
	case typeEnum:
		if desc.nullable {
			return "rawEnums['" + jsonName + "'] ?? " + dartName + "?.wire"
		}
		return "rawEnums['" + jsonName + "'] ?? " + dartName + ".wire"
	}
	return dartName
}

// encodeList emits a list assignment, converting struct elements back to
// JSON. A list of values that are already JSON stays a plain assignment.
func (g *generator) encodeList(desc *typeDesc, jsonName, dartName string) []string {
	elem := desc.elem
	if !elem.writesJSON() {
		return []string{"json['" + jsonName + "'] = " + dartName + ";"}
	}
	call := "value.toJson()"
	if elem.nullable {
		call = "value?.toJson()"
	}
	return []string{
		"json['" + jsonName + "'] = [",
		"  for (final value in " + dartName + ") " + call + ",",
		"];",
	}
}

// encodeMap emits a map assignment, converting values back to JSON. A map
// whose values are maps of structs nests the same literal, which is what a
// profile-to-role-to-binding document needs.
func (g *generator) encodeMap(desc *typeDesc, jsonName, dartName string) []string {
	if !writesJSONDeep(desc) {
		return []string{"json['" + jsonName + "'] = " + dartName + ";"}
	}
	return []string{"json['" + jsonName + "'] = " + mapLiteral(desc, dartName) + ";"}
}

// mapLiteral is the Dart expression that writes a Map<String, T> as JSON.
func mapLiteral(desc *typeDesc, expr string) string {
	elem := desc.elem
	item := "entry.value"
	switch elem.kind {
	case typeMap:
		item = mapLiteral(elem, "entry.value")
	case typeStruct, typeEnum:
		if elem.nullable {
			item = "entry.value?.toJson()"
		} else {
			item = "entry.value.toJson()"
		}
	}
	return "{for (final entry in " + expr + ".entries) entry.key: " + item + "}"
}

// writesJSONDeep reports whether a value of this type needs encoding back to
// JSON: a struct, an enum, or a map of either.
func writesJSONDeep(desc *typeDesc) bool {
	if desc.kind == typeMap {
		return writesJSONDeep(desc.elem)
	}
	return desc.writesJSON()
}

// typeKind is what a Dart field type is made of.
type typeKind int

const (
	typePrim typeKind = iota
	typeStruct
	typeEnum
	typeRaw
	typeList
	typeMap
)

// typeDesc is one field's Dart type, with the structure the decoder and the
// encoder need.
type typeDesc struct {
	kind     typeKind
	prim     string // "String", "int", "double" or "bool" for kindPrim
	name     string // the Dart class or enum name
	nullable bool   // the Go type is a pointer
	elem     *typeDesc
}

// dartText is the Dart type as written.
func (d *typeDesc) dartText() string {
	var s string
	switch d.kind {
	case typePrim:
		s = d.prim
	case typeStruct, typeEnum:
		s = d.name
	case typeRaw:
		s = "Object?"
	case typeList:
		s = "List<" + d.elem.dartText() + ">"
	case typeMap:
		s = "Map<String, " + d.elem.dartText() + ">"
	}
	if d.nullable && !strings.HasSuffix(s, "?") {
		s += "?"
	}
	return s
}

// writesJSON reports whether encoding a value of this type means calling its
// own toJson, rather than handing it to the JSON encoder as it is.
func (d *typeDesc) writesJSON() bool {
	return d.kind == typeStruct || d.kind == typeEnum
}

// describe reads one field type expression as a Dart type.
func (g *generator) describe(expr ast.Expr) (*typeDesc, error) {
	switch t := expr.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return &typeDesc{kind: typePrim, prim: "String"}, nil
		case "bool":
			return &typeDesc{kind: typePrim, prim: "bool"}, nil
		case "int", "int8", "int16", "int32", "int64",
			"uint", "uint8", "uint16", "uint32", "uint64", "uintptr", "byte", "rune":
			return &typeDesc{kind: typePrim, prim: "int"}, nil
		case "float32", "float64":
			return &typeDesc{kind: typePrim, prim: "double"}, nil
		}
		// complex64 and complex128 are not listed: unlike tsgen, which maps
		// them to `number`, this module has no Dart type for them, so the
		// fall-through below rejects them by name.
		if k, declared := g.kinds[t.Name]; declared {
			switch k {
			case kindString:
				if len(g.consts[t.Name]) == 0 {
					// A named string with no constants is just a string.
					return &typeDesc{kind: typePrim, prim: "String"}, nil
				}
				return &typeDesc{kind: typeEnum, name: t.Name}, nil
			case kindStruct:
				return &typeDesc{kind: typeStruct, name: t.Name}, nil
			default:
				construct := g.constructs[t.Name]
				if construct == "" {
					construct = fmt.Sprintf("type %q", t.Name)
				}
				return nil, g.unsupported(t.Pos(), construct)
			}
		}
		switch t.Name {
		case "any":
			return nil, g.unsupported(t.Pos(), "any")
		case "error":
			return nil, g.unsupported(t.Pos(), "error")
		}
		return nil, g.unsupported(t.Pos(), fmt.Sprintf("type %q", t.Name))
	case *ast.SelectorExpr:
		pkg, ok := t.X.(*ast.Ident)
		if !ok {
			return nil, g.unsupported(t.Pos(), "selector type")
		}
		switch pkg.Name + "." + t.Sel.Name {
		case "time.Time":
			return &typeDesc{kind: typePrim, prim: "String"}, nil
		case "json.RawMessage":
			return &typeDesc{kind: typeRaw}, nil
		}
		return nil, g.unsupported(t.Pos(), fmt.Sprintf("type %s.%s", pkg.Name, t.Sel.Name))
	case *ast.StarExpr:
		inner, err := g.describe(t.X)
		if err != nil {
			return nil, err
		}
		inner.nullable = true
		return inner, nil
	case *ast.ArrayType:
		if t.Len != nil {
			return nil, g.unsupported(t.Pos(), "array")
		}
		elem, err := g.describe(t.Elt)
		if err != nil {
			return nil, err
		}
		if elem.kind == typeEnum {
			// An enum inside a container has nowhere to keep the wire
			// text of a value this build does not know.
			return nil, g.unsupported(t.Pos(), "list of an enum type")
		}
		return &typeDesc{kind: typeList, elem: elem}, nil
	case *ast.MapType:
		key, ok := t.Key.(*ast.Ident)
		if !ok || key.Name != "string" {
			return nil, g.unsupported(t.Pos(), "map keyed by a non-string")
		}
		elem, err := g.describe(t.Value)
		if err != nil {
			return nil, err
		}
		if elem.kind == typeEnum {
			return nil, g.unsupported(t.Pos(), "map of an enum type")
		}
		return &typeDesc{kind: typeMap, elem: elem}, nil
	case *ast.StructType:
		return nil, g.unsupported(t.Pos(), "anonymous struct")
	case *ast.ChanType:
		return nil, g.unsupported(t.Pos(), "channel")
	case *ast.InterfaceType:
		return nil, g.unsupported(t.Pos(), "interface")
	case *ast.FuncType:
		return nil, g.unsupported(t.Pos(), "function type")
	case *ast.IndexExpr, *ast.IndexListExpr:
		return nil, g.unsupported(t.Pos(), "generic type")
	default:
		return nil, g.unsupported(expr.Pos(), "type expression")
	}
}

// nullableMark is the `?` a nullable Dart type takes.
func nullableMark(null bool) string {
	if null {
		return "?"
	}
	return ""
}

// lowerCamel renders a Go identifier in lower camel case: the leading run of
// capitals lowercased, keeping its last letter when the run starts a word of
// its own (MCPProjectID becomes mcpProjectID, AgentIdle becomes agentIdle).
//
// A name that is a Dart keyword is not rejected here: a field keeps its JSON
// name and takes a trailing underscore (see the field loop), so `extends` is
// expressible.
func lowerCamel(name string) (string, error) {
	if name == "" {
		return "", fmt.Errorf("empty identifier")
	}
	runes := []rune(name)
	end := 0
	for end < len(runes) && unicode.IsUpper(runes[end]) {
		end++
	}
	if end > 1 && end < len(runes) && unicode.IsLower(runes[end]) {
		end--
	}
	out := string(unicode.ToLower(runes[0])) + string(runes[1:])
	if end > 1 {
		out = strings.ToLower(string(runes[:end])) + string(runes[end:])
	}
	return out, nil
}

// dartReserved are the identifiers a Dart declaration or field may not take.
// A contextual keyword is not listed: `required`, `late` and the like are
// legal names.
var dartReserved = map[string]bool{
	"assert": true, "break": true, "case": true, "catch": true, "class": true,
	"const": true, "continue": true, "default": true, "do": true, "else": true,
	"enum": true, "extends": true, "false": true, "final": true,
	"finally": true, "for": true, "if": true, "in": true, "is": true,
	"new": true, "null": true, "rethrow": true, "return": true, "super": true,
	"switch": true, "this": true, "throw": true, "true": true, "try": true,
	"var": true, "void": true, "while": true, "with": true,
}

// checkDartIdentifier rejects a name Dart cannot declare.
func checkDartIdentifier(name string) error {
	if dartReserved[name] {
		return fmt.Errorf("%q is a Dart keyword", name)
	}
	if name == "unknown" {
		return fmt.Errorf("%q is the reserved unknown value", name)
	}
	return nil
}
