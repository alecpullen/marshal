// Package tsgen writes the TypeScript module for a contract package (P5 F1).
// Standard library only: it reads the package's syntax, never its compiled
// types.
package tsgen

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"strconv"
	"strings"
)

// header is the module's first two lines: what wrote the file and how to
// write it again.
const header = `// Code generated by web/bridge/contract/tsgen. DO NOT EDIT.
// Regenerate with: go test ./web/bridge/contract/tsgen -run TestTypeScriptContractIsCurrent -update
`

// kind is what a package-level named type means to the generator.
type kind int

const (
	kindOther kind = iota
	kindString
	kindStruct
	kindInterface
)

// file is one parsed source file, in lexical filename order.
type file struct {
	path string
	ast  *ast.File
}

// generator holds the parsed package: the declarations to emit and the
// constants that name their values.
type generator struct {
	fset   *token.FileSet
	files  []*file
	kinds  map[string]kind
	consts map[string][]string
}

// Generate reads the Go files of the package in dir, test files excluded,
// and returns the TypeScript module: a header line, then each named string
// type as a union and each struct as an interface, files in name order and
// declarations in source order.
func Generate(dir string) ([]byte, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}

	g := &generator{
		fset:   token.NewFileSet(),
		kinds:  make(map[string]kind),
		consts: make(map[string][]string),
	}

	pkg := ""
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		path := filepath.Join(dir, name)
		f, err := parser.ParseFile(g.fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		if pkg == "" {
			pkg = f.Name.Name
		} else if f.Name.Name != pkg {
			pos := g.fset.Position(f.Name.Pos())
			return nil, fmt.Errorf("%s:%d: package %q, want %q", pos.Filename, pos.Line, f.Name.Name, pkg)
		}
		g.files = append(g.files, &file{path: path, ast: f})
	}

	if err := g.collect(); err != nil {
		return nil, err
	}
	return g.render()
}

// collect records each package-level type's kind and each named string
// type's typed constants, both in source order across files.
func (g *generator) collect() error {
	for _, f := range g.files {
		for _, decl := range f.ast.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			switch gd.Tok {
			case token.TYPE:
				for _, spec := range gd.Specs {
					ts, ok := spec.(*ast.TypeSpec)
					if !ok {
						continue
					}
					if ts.TypeParams != nil && ts.TypeParams.NumFields() > 0 {
						return g.unsupported(ts.Pos(), "generic type")
					}
					g.kinds[ts.Name.Name] = classify(ts.Type)
				}
			case token.CONST:
				for _, spec := range gd.Specs {
					vs, ok := spec.(*ast.ValueSpec)
					if !ok {
						continue
					}
					id, ok := vs.Type.(*ast.Ident)
					if !ok || g.kinds[id.Name] != kindString {
						continue
					}
					for i := range vs.Names {
						if i >= len(vs.Values) {
							break
						}
						lit, ok := vs.Values[i].(*ast.BasicLit)
						if !ok || lit.Kind != token.STRING {
							continue
						}
						value, err := strconv.Unquote(lit.Value)
						if err != nil {
							pos := g.fset.Position(lit.Pos())
							return fmt.Errorf("%s:%d: unsupported constant value %s", pos.Filename, pos.Line, lit.Value)
						}
						g.consts[id.Name] = append(g.consts[id.Name], value)
					}
				}
			}
		}
	}
	return nil
}

// classify records what a type declaration may be referenced as.
func classify(expr ast.Expr) kind {
	switch t := expr.(type) {
	case *ast.StructType:
		return kindStruct
	case *ast.InterfaceType:
		return kindInterface
	case *ast.Ident:
		if t.Name == "string" {
			return kindString
		}
	}
	return kindOther
}

// render emits the module: the header, a blank line, then one block per
// declaration, separated by blank lines, ending with exactly one newline.
func (g *generator) render() ([]byte, error) {
	var blocks []string
	for _, f := range g.files {
		for _, decl := range f.ast.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				doc := ts.Doc
				if doc == nil && len(gd.Specs) == 1 {
					doc = gd.Doc
				}

				var block string
				var err error
				switch g.kinds[ts.Name.Name] {
				case kindString:
					block = g.stringUnion(ts.Name.Name, doc)
				case kindStruct:
					block, err = g.structInterface(ts.Name.Name, ts.Type.(*ast.StructType), doc)
					if err != nil {
						return nil, err
					}
				default:
					continue
				}
				blocks = append(blocks, block)
			}
		}
	}

	var b strings.Builder
	b.WriteString(header)
	if len(blocks) > 0 {
		b.WriteString("\n")
		b.WriteString(strings.Join(blocks, "\n\n"))
		b.WriteString("\n")
	}
	return []byte(b.String()), nil
}

// stringUnion emits a named string type: a union of its typed constants in
// declaration order, or plain string when it has none.
func (g *generator) stringUnion(name string, doc *ast.CommentGroup) string {
	var b strings.Builder
	writeDoc(&b, doc, "")
	values := g.consts[name]
	if len(values) == 0 {
		fmt.Fprintf(&b, "export type %s = string;", name)
		return b.String()
	}
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(v) + "'"
	}
	fmt.Fprintf(&b, "export type %s = %s;", name, strings.Join(quoted, " | "))
	return b.String()
}

// structInterface emits an exported-field interface for one struct.
func (g *generator) structInterface(name string, st *ast.StructType, doc *ast.CommentGroup) (string, error) {
	var b strings.Builder
	writeDoc(&b, doc, "")
	fmt.Fprintf(&b, "export interface %s {\n", name)

	for _, field := range st.Fields.List {
		if len(field.Names) == 0 {
			return "", g.unsupported(field.Pos(), "embedded field")
		}
		for _, ident := range field.Names {
			if !ident.IsExported() {
				continue
			}
			jsonName := ident.Name
			optional := false
			if field.Tag != nil {
				raw, err := strconv.Unquote(field.Tag.Value)
				if err != nil {
					return "", g.unsupported(field.Tag.Pos(), "struct tag")
				}
				if tag := reflect.StructTag(raw).Get("json"); tag != "" {
					parts := strings.Split(tag, ",")
					if parts[0] == "-" {
						continue
					}
					if parts[0] != "" {
						jsonName = parts[0]
					}
					for _, opt := range parts[1:] {
						if opt == "omitempty" {
							optional = true
						}
					}
				}
			}

			expr := field.Type
			pointer := false
			if star, ok := expr.(*ast.StarExpr); ok {
				pointer = true
				expr = star.X
			}
			tsType, err := g.tsType(expr)
			if err != nil {
				return "", err
			}
			if pointer && !optional {
				tsType += " | null"
			}

			writeDoc(&b, field.Doc, "  ")
			if field.Doc == nil {
				writeDoc(&b, field.Comment, "  ")
			}
			if optional {
				fmt.Fprintf(&b, "  %s?: %s;\n", jsonName, tsType)
			} else {
				fmt.Fprintf(&b, "  %s: %s;\n", jsonName, tsType)
			}
		}
	}

	b.WriteString("}")
	return b.String(), nil
}

// tsType maps one field type expression to TypeScript.
func (g *generator) tsType(expr ast.Expr) (string, error) {
	switch t := expr.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string", "bool":
			if t.Name == "string" {
				return "string", nil
			}
			return "boolean", nil
		case "int", "int8", "int16", "int32", "int64",
			"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
			"float32", "float64", "complex64", "complex128", "byte", "rune":
			return "number", nil
		}
		switch g.kinds[t.Name] {
		case kindInterface:
			return "", g.unsupported(t.Pos(), "interface")
		case kindString, kindStruct, kindOther:
			return t.Name, nil
		}
		return "", g.unsupported(t.Pos(), fmt.Sprintf("type %q", t.Name))
	case *ast.SelectorExpr:
		pkg, ok := t.X.(*ast.Ident)
		if !ok {
			return "", g.unsupported(t.Pos(), "selector type")
		}
		switch pkg.Name + "." + t.Sel.Name {
		case "time.Time":
			return "string", nil
		case "json.RawMessage":
			return "unknown", nil
		}
		return "", g.unsupported(t.Pos(), fmt.Sprintf("type %s.%s", pkg.Name, t.Sel.Name))
	case *ast.StarExpr:
		inner, err := g.tsType(t.X)
		if err != nil {
			return "", err
		}
		return inner + " | null", nil
	case *ast.ArrayType:
		if t.Len != nil {
			return "", g.unsupported(t.Pos(), "array")
		}
		inner, err := g.tsType(t.Elt)
		if err != nil {
			return "", err
		}
		return inner + "[]", nil
	case *ast.MapType:
		key, ok := t.Key.(*ast.Ident)
		if !ok || key.Name != "string" {
			return "", g.unsupported(t.Pos(), "map keyed by a non-string")
		}
		value, err := g.tsType(t.Value)
		if err != nil {
			return "", err
		}
		return "Record<string, " + value + ">", nil
	case *ast.StructType:
		return "", g.unsupported(t.Pos(), "anonymous struct")
	case *ast.ChanType:
		return "", g.unsupported(t.Pos(), "channel")
	case *ast.InterfaceType:
		return "", g.unsupported(t.Pos(), "interface")
	case *ast.FuncType:
		return "", g.unsupported(t.Pos(), "function type")
	case *ast.IndexExpr, *ast.IndexListExpr:
		return "", g.unsupported(t.Pos(), "generic type")
	default:
		return "", g.unsupported(expr.Pos(), "type expression")
	}
}

// unsupported names the file, line and construct that has no mapping.
func (g *generator) unsupported(pos token.Pos, construct string) error {
	p := g.fset.Position(pos)
	return fmt.Errorf("%s:%d: unsupported %s", p.Filename, p.Line, construct)
}

// writeDoc renders a Go doc comment as a TypeScript block comment, each line
// indented by indent. An absent or empty comment writes nothing.
func writeDoc(b *strings.Builder, doc *ast.CommentGroup, indent string) {
	if doc == nil {
		return
	}
	text := strings.TrimSuffix(doc.Text(), "\n")
	if text == "" {
		return
	}
	b.WriteString(indent + "/**\n")
	for _, line := range strings.Split(text, "\n") {
		if line == "" {
			b.WriteString(indent + " *\n")
			continue
		}
		b.WriteString(indent + " * " + line + "\n")
	}
	b.WriteString(indent + " */\n")
}
