// Package tsgen writes the TypeScript module for a contract package (P5 F1).
// Standard library only: it reads the package's syntax, never its compiled
// types.
package tsgen

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"strconv"
	"strings"
)

// header is the module's first two lines: what wrote the file and how to
// write it again.
const header = `// Code generated by web/bridge/contract/tsgen. DO NOT EDIT.
// Regenerate with: go test ./web/bridge/contract/tsgen -run TestTypeScriptContractIsCurrent -update
`

// kind is what a package-level named type means to the generator.
type kind int

const (
	// kindUnsupported is a named type the module cannot declare. A field
	// naming one is an error, never a reference to a TypeScript type that
	// does not exist. It is the zero kind, so a name the package never
	// declared is unsupported too.
	kindUnsupported kind = iota
	// kindString is a named string type: it becomes a union of its
	// constants' values.
	kindString
	// kindStruct is a named struct: it becomes an interface.
	kindStruct
	// kindInterface is a named interface, which the plan does not map.
	kindInterface
)

// file is one parsed source file, in lexical filename order.
type file struct {
	path string
	ast  *ast.File
}

// generator holds the parsed package: the declarations to emit and the
// constants that name their values.
type generator struct {
	fset  *token.FileSet
	files []*file
	kinds map[string]kind
	// constructs names the unsupported construct of each declared type the
	// module cannot map, so a field naming it says why.
	constructs map[string]string
	// rawTypes holds each declared type's underlying expression, so a type
	// declared as another type can be resolved.
	rawTypes map[string]ast.Expr
	// consts holds each named string type's constant values, in
	// declaration order.
	consts map[string][]string
	// constDecls holds each named string type's constant declarations, in
	// declaration order.
	constDecls map[string][]constDecl
	// constExprs holds every constant's value expression, by name, so a
	// constant that takes its value from another constant resolves.
	constExprs map[string]ast.Expr
}

// constDecl is one constant of a named string type: its name and the
// expression that gives its value.
type constDecl struct {
	name string
	expr ast.Expr
}

// Generate reads the Go files of the package in dir, test files excluded,
// and returns the TypeScript module: a header line, then each named string
// type as a union and each struct as an interface, files in name order and
// declarations in source order.
func Generate(dir string) ([]byte, error) {
	g, err := newGenerator(dir)
	if err != nil {
		return nil, err
	}
	if err := g.collect(); err != nil {
		return nil, err
	}
	return g.render()
}

// newGenerator parses the Go files of the package in dir, test files
// excluded, in lexical filename order.
func newGenerator(dir string) (*generator, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}

	g := &generator{
		fset:       token.NewFileSet(),
		kinds:      make(map[string]kind),
		constructs: make(map[string]string),
		rawTypes:   make(map[string]ast.Expr),
		consts:     make(map[string][]string),
		constDecls: make(map[string][]constDecl),
		constExprs: make(map[string]ast.Expr),
	}

	pkg := ""
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		path := filepath.Join(dir, name)
		f, err := parser.ParseFile(g.fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		if pkg == "" {
			pkg = f.Name.Name
		} else if f.Name.Name != pkg {
			pos := g.fset.Position(f.Name.Pos())
			return nil, fmt.Errorf("%s:%d: package %q, want %q", pos.Filename, pos.Line, f.Name.Name, pkg)
		}
		g.files = append(g.files, &file{path: path, ast: f})
	}

	return g, nil
}

// collect records each package-level type's kind and each named string
// type's typed constants, both in source order across files.
func (g *generator) collect() error {
	// The types come first, in their own pass: a constant may name a type
	// declared later, or in a later file.
	if err := g.collectTypes(); err != nil {
		return err
	}
	g.resolveTypes()
	if err := g.collectConstants(); err != nil {
		return err
	}
	return g.resolveConstants()
}

// collectTypes records what each package-level type declaration means.
func (g *generator) collectTypes() error {
	for _, f := range g.files {
		for _, decl := range f.ast.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				if ts.TypeParams != nil && ts.TypeParams.NumFields() > 0 {
					return g.unsupported(ts.Pos(), "generic type")
				}
				if ts.Assign.IsValid() {
					// An alias names another type, and the generator
					// maps types by declaration, not by target.
					g.kinds[ts.Name.Name] = kindUnsupported
					g.constructs[ts.Name.Name] = "type alias"
					continue
				}
				k, construct := classify(ts.Type, ts.Name.Name)
				g.kinds[ts.Name.Name] = k
				g.rawTypes[ts.Name.Name] = ts.Type
				if construct != "" {
					g.constructs[ts.Name.Name] = construct
				}
			}
		}
	}
	return nil
}

// resolveTypes settles each type declared as another type. One declared as
// a named string type is a string type itself, and its own constants make
// its union.
func (g *generator) resolveTypes() {
	for name := range g.rawTypes {
		if g.kinds[name] != kindUnsupported {
			continue
		}
		ident, ok := g.rawTypes[name].(*ast.Ident)
		if !ok {
			continue
		}
		if g.stringKind(ident.Name, map[string]bool{}) {
			g.kinds[name] = kindString
			g.constructs[name] = ""
		}
	}
}

// stringKind reports whether the named type is a string type, following the
// chain of types declared as other types.
func (g *generator) stringKind(name string, seen map[string]bool) bool {
	if seen[name] {
		return false
	}
	seen[name] = true
	switch g.kinds[name] {
	case kindString:
		return true
	case kindUnsupported:
	default:
		return false
	}
	expr, ok := g.rawTypes[name]
	if !ok {
		return false
	}
	ident, ok := expr.(*ast.Ident)
	if !ok {
		return false
	}
	return g.stringKind(ident.Name, seen)
}

// collectConstants records each named string type's typed constants, in
// declaration order across files.
func (g *generator) collectConstants() error {
	for _, f := range g.files {
		for _, decl := range f.ast.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.CONST {
				continue
			}
			// A const block may omit an expression list, which repeats the
			// previous non-empty list and its type.
			var lastValues []ast.Expr
			var lastType ast.Expr
			for _, spec := range gd.Specs {
				vs, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				values, typ := vs.Values, vs.Type
				if len(values) == 0 {
					values = lastValues
					if typ == nil {
						typ = lastType
					}
				} else {
					lastValues, lastType = values, vs.Type
				}
				for i, name := range vs.Names {
					if i >= len(values) {
						break
					}
					// Every constant's expression is recorded, so a
					// constant that takes its value from another
					// constant resolves.
					g.constExprs[name.Name] = values[i]
					id, ok := typ.(*ast.Ident)
					if !ok || g.kinds[id.Name] != kindString {
						continue
					}
					g.constDecls[id.Name] = append(g.constDecls[id.Name], constDecl{name: name.Name, expr: values[i]})
				}
			}
		}
	}
	return nil
}

// resolveConstants turns each named string type's constant declarations into
// their values, in declaration order.
func (g *generator) resolveConstants() error {
	for name, decls := range g.constDecls {
		values := make([]string, 0, len(decls))
		for _, d := range decls {
			value, err := g.constValue(d.expr, map[string]bool{})
			if err != nil {
				return err
			}
			values = append(values, value)
		}
		g.consts[name] = values
	}
	return nil
}

// constValue reads one constant's value: a string literal, or the value of
// the constant it names.
func (g *generator) constValue(expr ast.Expr, seen map[string]bool) (string, error) {
	switch t := expr.(type) {
	case *ast.BasicLit:
		if t.Kind != token.STRING {
			return "", g.unsupported(t.Pos(), "constant value")
		}
		value, err := strconv.Unquote(t.Value)
		if err != nil {
			return "", g.unsupported(t.Pos(), "constant value")
		}
		return value, nil
	case *ast.ParenExpr:
		return g.constValue(t.X, seen)
	case *ast.Ident:
		if seen[t.Name] {
			return "", g.unsupported(t.Pos(), "constant value")
		}
		next, ok := g.constExprs[t.Name]
		if !ok {
			return "", g.unsupported(t.Pos(), fmt.Sprintf("constant %q", t.Name))
		}
		seen[t.Name] = true
		defer delete(seen, t.Name)
		return g.constValue(next, seen)
	default:
		return "", g.unsupported(expr.Pos(), "constant value")
	}
}

// classify records what a type declaration may be referenced as, and the
// construct to name when it has no TypeScript mapping. A named type the
// module cannot declare is unsupported: a field naming it would be a
// reference to a TypeScript type that does not exist.
func classify(expr ast.Expr, name string) (kind, string) {
	switch t := expr.(type) {
	case *ast.StructType:
		return kindStruct, ""
	case *ast.InterfaceType:
		return kindInterface, "interface"
	case *ast.Ident:
		if t.Name == "string" {
			return kindString, ""
		}
		// A type declared as another type: it is settled once every
		// type is known.
		return kindUnsupported, ""
	case *ast.ChanType:
		return kindUnsupported, "channel"
	case *ast.FuncType:
		return kindUnsupported, "function type"
	case *ast.ArrayType:
		if t.Len != nil {
			return kindUnsupported, "array"
		}
		return kindUnsupported, "slice"
	case *ast.MapType:
		key, ok := t.Key.(*ast.Ident)
		if !ok || key.Name != "string" {
			return kindUnsupported, "map keyed by a non-string"
		}
		return kindUnsupported, "map"
	case *ast.StarExpr:
		return kindUnsupported, "pointer type"
	case *ast.IndexExpr, *ast.IndexListExpr:
		return kindUnsupported, "generic type"
	default:
		return kindUnsupported, fmt.Sprintf("named type %q", name)
	}
}

// render emits the module: the header, a blank line, then one block per
// declaration, separated by blank lines, ending with exactly one newline.
func (g *generator) render() ([]byte, error) {
	var blocks []string
	for _, f := range g.files {
		for _, decl := range f.ast.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				doc := ts.Doc
				if doc == nil && len(gd.Specs) == 1 {
					doc = gd.Doc
				}

				var block string
				var err error
				switch g.kinds[ts.Name.Name] {
				case kindString:
					block = g.stringUnion(ts.Name.Name, doc)
				case kindStruct:
					block, err = g.structInterface(ts.Name.Name, ts.Type.(*ast.StructType), doc)
					if err != nil {
						return nil, err
					}
				default:
					continue
				}
				blocks = append(blocks, block)
			}
		}
	}

	var b strings.Builder
	b.WriteString(header)
	if len(blocks) > 0 {
		b.WriteString("\n")
		b.WriteString(strings.Join(blocks, "\n\n"))
		b.WriteString("\n")
	}
	return []byte(b.String()), nil
}

// stringUnion emits a named string type: a union of its typed constants in
// declaration order, or plain string when it has none.
func (g *generator) stringUnion(name string, doc *ast.CommentGroup) string {
	var b strings.Builder
	writeDoc(&b, doc, "")
	values := g.consts[name]
	if len(values) == 0 {
		fmt.Fprintf(&b, "export type %s = string;", name)
		return b.String()
	}
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = tsString(v)
	}
	fmt.Fprintf(&b, "export type %s = %s;", name, strings.Join(quoted, " | "))
	return b.String()
}

// tsString renders a Go string value as a single-quoted TypeScript literal.
func tsString(value string) string {
	var b strings.Builder
	b.WriteByte('\'')
	for _, r := range value {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '\'':
			b.WriteString(`\'`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 {
				fmt.Fprintf(&b, `\u%04x`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('\'')
	return b.String()
}

// structInterface emits an exported-field interface for one struct.
func (g *generator) structInterface(name string, st *ast.StructType, doc *ast.CommentGroup) (string, error) {
	var b strings.Builder
	writeDoc(&b, doc, "")
	fmt.Fprintf(&b, "export interface %s {\n", name)

	for _, field := range st.Fields.List {
		if len(field.Names) == 0 {
			return "", g.unsupported(field.Pos(), "embedded field")
		}
		for _, ident := range field.Names {
			if !ident.IsExported() {
				continue
			}
			jsonName := ident.Name
			optional := false
			if field.Tag != nil {
				raw, err := strconv.Unquote(field.Tag.Value)
				if err != nil {
					return "", g.unsupported(field.Tag.Pos(), "struct tag")
				}
				if tag := reflect.StructTag(raw).Get("json"); tag != "" {
					parts := strings.Split(tag, ",")
					if parts[0] == "-" {
						continue
					}
					if parts[0] != "" {
						jsonName = parts[0]
					}
					for _, opt := range parts[1:] {
						if opt == "omitempty" {
							optional = true
						}
					}
				}
			}

			expr := field.Type
			pointer := false
			if star, ok := expr.(*ast.StarExpr); ok {
				pointer = true
				expr = star.X
			}
			tsType, _, err := g.tsType(expr)
			if err != nil {
				return "", err
			}
			if pointer && !optional {
				tsType += " | null"
			}

			writeDoc(&b, field.Doc, "  ")
			if field.Doc == nil {
				writeDoc(&b, field.Comment, "  ")
			}
			if optional {
				fmt.Fprintf(&b, "  %s?: %s;\n", jsonName, tsType)
			} else {
				fmt.Fprintf(&b, "  %s: %s;\n", jsonName, tsType)
			}
		}
	}

	b.WriteString("}")
	return b.String(), nil
}

// tsType maps one field type expression to TypeScript. It also reports
// whether the result is a union, which must be parenthesised before it is
// used as an array element.
func (g *generator) tsType(expr ast.Expr) (string, bool, error) {
	switch t := expr.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "string", false, nil
		case "bool":
			return "boolean", false, nil
		case "int", "int8", "int16", "int32", "int64",
			"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
			"float32", "float64", "complex64", "complex128", "byte", "rune":
			return "number", false, nil
		}
		if kind, declared := g.kinds[t.Name]; declared {
			switch kind {
			case kindString, kindStruct:
				return t.Name, false, nil
			default:
				construct := g.constructs[t.Name]
				if construct == "" {
					construct = fmt.Sprintf("type %q", t.Name)
				}
				return "", false, g.unsupported(t.Pos(), construct)
			}
		}
		// A name the package never declared: any, error, or a typo.
		switch t.Name {
		case "any":
			return "", false, g.unsupported(t.Pos(), "any")
		case "error":
			return "", false, g.unsupported(t.Pos(), "error")
		}
		return "", false, g.unsupported(t.Pos(), fmt.Sprintf("type %q", t.Name))
	case *ast.SelectorExpr:
		pkg, ok := t.X.(*ast.Ident)
		if !ok {
			return "", false, g.unsupported(t.Pos(), "selector type")
		}
		switch pkg.Name + "." + t.Sel.Name {
		case "time.Time":
			return "string", false, nil
		case "json.RawMessage":
			return "unknown", false, nil
		}
		return "", false, g.unsupported(t.Pos(), fmt.Sprintf("type %s.%s", pkg.Name, t.Sel.Name))
	case *ast.StarExpr:
		inner, union, err := g.tsType(t.X)
		if err != nil {
			return "", false, err
		}
		if union {
			// A union binds looser than "|", so it needs its own
			// parentheses.
			inner = "(" + inner + ")"
		}
		return inner + " | null", true, nil
	case *ast.ArrayType:
		if t.Len != nil {
			return "", false, g.unsupported(t.Pos(), "array")
		}
		inner, union, err := g.tsType(t.Elt)
		if err != nil {
			return "", false, err
		}
		if union {
			// A union binds looser than "[]", so it needs its own
			// parentheses: (T | null)[], not T | null[].
			inner = "(" + inner + ")"
		}
		return inner + "[]", false, nil
	case *ast.MapType:
		key, ok := t.Key.(*ast.Ident)
		if !ok || key.Name != "string" {
			return "", false, g.unsupported(t.Pos(), "map keyed by a non-string")
		}
		value, _, err := g.tsType(t.Value)
		if err != nil {
			return "", false, err
		}
		return "Record<string, " + value + ">", false, nil
	case *ast.StructType:
		return "", false, g.unsupported(t.Pos(), "anonymous struct")
	case *ast.ChanType:
		return "", false, g.unsupported(t.Pos(), "channel")
	case *ast.InterfaceType:
		return "", false, g.unsupported(t.Pos(), "interface")
	case *ast.FuncType:
		return "", false, g.unsupported(t.Pos(), "function type")
	case *ast.IndexExpr, *ast.IndexListExpr:
		return "", false, g.unsupported(t.Pos(), "generic type")
	default:
		return "", false, g.unsupported(expr.Pos(), "type expression")
	}
}

// unsupported names the file, line and construct that has no mapping.
func (g *generator) unsupported(pos token.Pos, construct string) error {
	p := g.fset.Position(pos)
	return fmt.Errorf("%s:%d: unsupported %s", p.Filename, p.Line, construct)
}

// writeDoc renders a Go doc comment as a TypeScript block comment, each line
// indented by indent. An absent or empty comment writes nothing.
func writeDoc(b *strings.Builder, doc *ast.CommentGroup, indent string) {
	if doc == nil {
		return
	}
	text := strings.TrimSuffix(doc.Text(), "\n")
	if text == "" {
		return
	}
	// A "*/" would end the TypeScript block comment early.
	text = strings.ReplaceAll(text, "*/", `*\/`)
	b.WriteString(indent + "/**\n")
	for _, line := range strings.Split(text, "\n") {
		if line == "" {
			b.WriteString(indent + " *\n")
			continue
		}
		b.WriteString(indent + " * " + line + "\n")
	}
	b.WriteString(indent + " */\n")
}
